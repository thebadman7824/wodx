/**
 * Writes the line skins from skins-data.mjs (B91 to B95), split by line (B6060 to B6062):
 *   modules/wodx-sheets/styles/wodx-skins.css        the fonts and the loading rule, loaded on every page
 *   modules/wodx-sheets/styles/skins/<line>.css      one line's light and dark skin, loaded when its sheet opens
 *   modules/wodx-sheets/scripts/skins-index.mjs      the order of the lines and the sheet each one dresses
 * Run from the repo root: node tools/skins/build-skins.mjs
 * These are generated: change skins-data.mjs and run this again, never edit them by hand.
 */
import {mkdirSync, readdirSync, rmSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {LINES, FONTS, rule} from "./skins-data.mjs";

const SHEETS = fileURLToPath(new URL("../../modules/wodx-sheets/", import.meta.url));
const OUT = `${SHEETS}styles/wodx-skins.css`, LINE_DIR = `${SHEETS}styles/skins`, INDEX = `${SHEETS}scripts/skins-index.mjs`;
// A noise tile carries its own size; gradients fill the page
const sizeOf = layer => { const m = /width%3D'(\d+)'/.exec(layer) ?? /width='(\d+)'/.exec(layer); return m ? `${m[1]}px ${m[1]}px` : "100% 100%"; };

// WoDX Sheets puts its sheet class (wodx-kote, wodx-inqDA and the rest) on the sheet's form, inside the window that
// carries the system's line class, so those are matched with :has()
const onWindow = sel => sel.replace(/\.wodx-[A-Za-z0-9]+/g, m => `:has(${m})`);

const HEAD = [
  "/* WoDX line skins for the system's character sheets. GENERATED by tools/skins/build-skins.mjs from skins-data.mjs: do not edit by hand.",
  "   On only while the world setting \"Sheet look\" is WoDX (body.wodx-skin). Fonts: SIL Open Font License, see ../fonts/licenses.",
  "   Rules and papers are drawn by WoDX (SVG and CSS). */",
  ""
];
const fontFaces = () => FONTS.map(([family, file, weight]) =>
  `@font-face { font-family: "${family}"; src: url("../fonts/${file}") format("woff2"); font-weight: ${weight ?? "400"}; font-display: swap; }`);

/** The sheet a line dresses, as one selector the loader can match against a sheet's window (no body, no tone). */
export const testOf = L => L.sel.map(s => `.wod20.wod-sheet${onWindow(s)}`).join(", ");

/** One line's rules: its light and dark skin and its title face, as the single stylesheet had them. */
export function lineCss(L) {
  const out = [`/* ---- ${L.label} ---- */`];
  for ( const tone of ["light", "dark"] ) {
    const t = L[tone];
    const toneSel = tone === "dark" ? ".wod-theme-dark" : ":not(.wod-theme-dark)";
    const roots = L.sel.map(s => `body.wodx-skin .wod20.wod-sheet${onWindow(s)}${toneSel}`);
    const each = suffix => roots.map(r => r + suffix).join(",\n");
    out.push(`${each("")} {`,
      `  --sheet-background-color: ${t.base};`,
      `  --wx-skin-base: ${t.base};`,
      `  --wx-skin-ink: ${t.ink};`,
      `  --wx-skin-accent: ${t.acc};`,
      "}");
    out.push(`${each(" .window-content")} {`,
      `  background: ${[...t.layers, ""].map((x, i) => i < t.layers.length ? x : t.base).join(",\n    ")};`,
      `  background-size: ${[...t.layers.map(sizeOf), "auto"].join(", ")};`,
      "  background-repeat: repeat;",
      `  color: ${t.ink};`,
      "}");
    // The system also sets the banner variables on inner era blocks (.vampire .modern and the like) and clears the
    // banners in dark mode, so the rules are set on the banners themselves
    out.push(`${each(" .sheet-banner")} {`, `  background: ${rule(L.rule, t.rule, t.acc)} center / 75% auto no-repeat;`, "}",
      `${each(" .sheet-banner-small")} {`, `  background: ${rule(L.rule, t.rule, t.acc, true)} center / 100% auto no-repeat;`, "}",
      `${each(" .sheet-banner-text")} {`, `  background: radial-gradient(farthest-side, ${t.base} 70%, transparent);`, "  border-radius: 0;", "  padding: 0 .7em;", `  color: ${t.ink};`, "  position: static;", "}");
  }
  const fontRoots = L.sel.map(s => `body.wodx-skin .wod20.wod-sheet${onWindow(s)}:not(.noSplatFont) :is(.splatFont, .splatFont .sheet-banner-text)`);
  out.push(`${fontRoots.join(",\n")} {`, `  font-family: "${L.title}", var(--main-font);`, "}", "");
  return out.join("\n");
}

/** Every line in one stylesheet, as before the split (B91 to B95). The split files must add up to exactly this. */
export function buildCss() {
  return [...HEAD, ...fontFaces(), "", ...LINES.map(lineCss)].join("\n");
}

// While a sheet's skin file is still on its way, the sheet's page waits blank rather than showing the system's look
// for a moment (B6061)
const WAIT = [
  "/* While a sheet's own skin file loads (scripts/skins.mjs), its page waits rather than flashing the system's look. */",
  "body.wodx-skin .wod20.wod-sheet.wodx-wait-skin .window-content { visibility: hidden; }",
  ""
];

/** The split (B6060): the core sheet loaded on every page, one file per line, and the loader's index. */
export function buildSplit() {
  const core = [...HEAD, ...fontFaces(), "", ...WAIT].join("\n");
  const lines = Object.fromEntries(LINES.map(L => [L.id, [
    `/* WoDX line skin: ${L.label}. GENERATED by tools/skins/build-skins.mjs from skins-data.mjs: do not edit by hand.`,
    "   Loaded by scripts/skins.mjs when a sheet of this line opens. Fonts are declared in ../wodx-skins.css. */",
    "",
    lineCss(L)
  ].join("\n")]));
  const index = [
    "// GENERATED by tools/skins/build-skins.mjs from skins-data.mjs: do not edit by hand (B6060).",
    "// The line skins in the order the single stylesheet had them (the cascade keeps that order), and the sheet each dresses.",
    "export const SKINS = [",
    ...LINES.map(L => `  { id: ${JSON.stringify(L.id)}, test: ${JSON.stringify(testOf(L))} },`),
    "];",
    ""
  ].join("\n");
  return {core, lines, index};
}

if ( process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] ) {
  const {core, lines, index} = buildSplit();
  writeFileSync(OUT, core);
  mkdirSync(LINE_DIR, {recursive: true});
  // A line that left skins-data.mjs takes its file with it
  for ( const f of readdirSync(LINE_DIR) ) if ( f.endsWith(".css") && !(f.slice(0, -4) in lines) ) rmSync(`${LINE_DIR}/${f}`);
  for ( const [id, css] of Object.entries(lines) ) writeFileSync(`${LINE_DIR}/${id}.css`, css);
  writeFileSync(INDEX, index);
  const kb = t => (t.length / 1024).toFixed(1);
  console.log(`wrote ${OUT} (${kb(core)} KB), ${Object.keys(lines).length} line skins in ${LINE_DIR} (${Object.entries(lines).map(([id, c]) => `${id} ${kb(c)}`).join(", ")} KB), ${INDEX}`);
}
