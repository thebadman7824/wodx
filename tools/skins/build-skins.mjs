/**
 * Writes modules/wodx-sheets/styles/wodx-skins.css from skins-data.mjs (B91 to B95).
 * Run from the repo root: node tools/skins/build-skins.mjs
 * The stylesheet is generated: change skins-data.mjs and run this again, never edit the CSS by hand.
 */
import {writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {LINES, FONTS, rule} from "./skins-data.mjs";

const OUT = fileURLToPath(new URL("../../modules/wodx-sheets/styles/wodx-skins.css", import.meta.url));
// A noise tile carries its own size; gradients fill the page
const sizeOf = layer => { const m = /width%3D'(\d+)'/.exec(layer) ?? /width='(\d+)'/.exec(layer); return m ? `${m[1]}px ${m[1]}px` : "100% 100%"; };

// WoDX Sheets puts its sheet class (wodx-kote, wodx-inqDA and the rest) on the sheet's form, inside the window that
// carries the system's line class, so those are matched with :has()
const onWindow = sel => sel.replace(/\.wodx-[A-Za-z0-9]+/g, m => `:has(${m})`);

export function buildCss() {
  const out = [
    "/* WoDX line skins for the system's character sheets. GENERATED by tools/skins/build-skins.mjs from skins-data.mjs: do not edit by hand.",
    "   On only while the world setting \"Sheet look\" is WoDX (body.wodx-skin). Fonts: SIL Open Font License, see ../fonts/licenses.",
    "   Rules and papers are drawn by WoDX (SVG and CSS). */",
    ""
  ];
  for ( const [family, file, weight] of FONTS ) {
    out.push(`@font-face { font-family: "${family}"; src: url("../fonts/${file}") format("woff2"); font-weight: ${weight ?? "400"}; font-display: swap; }`);
  }
  out.push("");
  for ( const L of LINES ) {
    out.push(`/* ---- ${L.label} ---- */`);
    for ( const tone of ["light", "dark"] ) {
      const t = L[tone];
      const toneSel = tone === "dark" ? ".wod-theme-dark" : ":not(.wod-theme-dark)";
      const roots = L.sel.map(s => `body.wodx-skin .wod20.wod-sheet${onWindow(s)}${toneSel}`);
      const each = suffix => roots.map(r => r + suffix).join(",\n");
      out.push(`${each("")} {`,
        `  --sheet-background-color: ${t.base};`,
        `  --wx-skin-base: ${t.base};`,
        `  --wx-skin-ink: ${t.ink};`,
        `  --wx-skin-accent: ${t.acc};`,
        "}");
      out.push(`${each(" .window-content")} {`,
        `  background: ${[...t.layers, ""].map((x, i) => i < t.layers.length ? x : t.base).join(",\n    ")};`,
        `  background-size: ${[...t.layers.map(sizeOf), "auto"].join(", ")};`,
        "  background-repeat: repeat;",
        `  color: ${t.ink};`,
        "}");
      // The system also sets the banner variables on inner era blocks (.vampire .modern and the like) and clears the
      // banners in dark mode, so the rules are set on the banners themselves
      out.push(`${each(" .sheet-banner")} {`, `  background: ${rule(L.rule, t.rule, t.acc)} center / 75% auto no-repeat;`, "}",
        `${each(" .sheet-banner-small")} {`, `  background: ${rule(L.rule, t.rule, t.acc, true)} center / 100% auto no-repeat;`, "}",
        `${each(" .sheet-banner-text")} {`, `  background: radial-gradient(farthest-side, ${t.base} 70%, transparent);`, "  border-radius: 0;", "  padding: 0 .7em;", `  color: ${t.ink};`, "  position: static;", "}");
    }
    const fontRoots = L.sel.map(s => `body.wodx-skin .wod20.wod-sheet${onWindow(s)}:not(.noSplatFont) :is(.splatFont, .splatFont .sheet-banner-text)`);
    out.push(`${fontRoots.join(",\n")} {`, `  font-family: "${L.title}", var(--main-font);`, "}", "");
  }
  return out.join("\n");
}

if ( process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] ) {
  const css = buildCss();
  writeFileSync(OUT, css);
  console.log(`wrote ${OUT} (${(css.length / 1024).toFixed(1)} KB)`);
}
