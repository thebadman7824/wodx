/**
 * Builds modules/wodx-chronicle/data/future-world.mjs: the Future Darkness branch's own world history (kind F of
 * docs/research/era-timelines/r3/future-darkness.txt, B5890), as dated events of the Chronicle that carry a region.
 * Each one happens on its date like any other dated event, but the card only tells it where the news is heard
 * (the homeland's part of the world, or the part a scene stands in): see newsCodes in events-rules.mjs.
 * Run: node tools/wofd/build-future-world.mjs
 */
import fs from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname, join} from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const src = join(root, "docs/research/era-timelines/r3/future-darkness.txt");
const out = join(root, "modules/wodx-chronicle/data/future-world.mjs");
const REGIONS = new Set(["MO", "EU", "ME", "AS", "AF", "AM", "OC"]);
/** Places that belong to one chronicle (Chronicle Packs Desk b2): their events go to that chronicle's module, not the
 * shared world, and keep their ids. place -> {chronicle, file}. */
export const CHRONICLE_PLACES = {Rothenstein: {chronicle: "rothenstein", file: "modules/wodx-rothenstein/data/world-events.mjs"}};

/** The shared world's events; with {chronicle: id}, that chronicle's own instead (ids counted over both, so they never move). */
export function parse(text, {chronicle = null} = {}) {
  const events = [], count = {};
  for ( const raw of text.split("\n") ) {
    const line = raw.trim();
    if ( !line || line.startsWith("#") ) continue;
    const [ym, kind, , region, place, tags, title, summary] = line.split("|").map(s => s.trim());
    if ( kind !== "F" ) continue;
    if ( !REGIONS.has(region) ) throw new Error(`region ${region}: ${line}`);
    const [y, m] = ym.split("-").map(Number);
    const key = `${y}-${region.toLowerCase()}`;
    count[key] = (count[key] ?? 0) + 1;
    const own = CHRONICLE_PLACES[place]?.chronicle ?? null;
    if ( own !== chronicle ) continue;
    events.push({id: `fdw-${key}-${count[key]}`, year: y, ...(m ? {month: m} : {}), branch: "future", lines: ["mortal"],
      name: title, summary, region, place, tags: tags.split(",").map(s => s.trim()).filter(Boolean),
      source: "House history: the Future Darkness branch's world", ...(own ? {chronicle: own} : {})});
  }
  return events;
}

if ( process.argv[1] === fileURLToPath(import.meta.url) ) {
  const events = parse(fs.readFileSync(src, "utf8"));
  const head = `/**
 * GENERATED by tools/wofd/build-future-world.mjs from docs/research/era-timelines/r3/future-darkness.txt. Do not edit by hand.
 * The Future Darkness branch's world history, 1990 to 2099 (B5890): ${events.length} dated events, each with the part of the world
 * it happens in (MO Moravia, EU Europe, ME the Middle East, AS Asia, AF Africa, AM the Americas, OC Oceania) and its place.
 */
`;
  fs.writeFileSync(out, `${head}export default ${JSON.stringify({version: 1, events}, null, 1)};\n`);
  console.log(`${events.length} events written to ${out}`);
  for ( const {chronicle, file} of Object.values(CHRONICLE_PLACES) ) {
    const own = parse(fs.readFileSync(src, "utf8"), {chronicle});
    fs.writeFileSync(join(root, file), `/**
 * GENERATED by tools/wofd/build-future-world.mjs from docs/research/era-timelines/r3/future-darkness.txt. Do not edit by hand.
 * The Future Darkness branch's world events that belong to the chronicle "${chronicle}" (Chronicle Packs Desk b2): they
 * happen only while this chronicle is in play. ${own.length} events.
 */
export default ${JSON.stringify({version: 1, events: own}, null, 1)};\n`);
    console.log(`${own.length} events written to ${file}`);
  }
}
