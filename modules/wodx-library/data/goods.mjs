/**
 * Containers stay out of a good's name (Ben, 2026-11-11): "claret", not "a bottle of claret". A row may still be
 * written "a bottle of claret": the name becomes "claret", good.container "a bottle" (what it is usually kept in,
 * never added to a line or an item: Ben, 2026-11-12), and good.former keeps the written form, which the tables
 * above (stack sizes, overrides, descriptions) and older items use.
 * A row whose measure is the thing itself (a pack of playing cards, a can of pepper spray, a sack of coarse cloth)
 * is left as written. Reverse by emptying CONTAINER_WORDS.
 */
export const CONTAINER_WORDS = ["sack", "bag", "crock", "jug", "jar", "pot", "twist", "pouch", "paper", "paper bag", "packet", "tin",
  "box", "tube", "cask", "bottle", "six-pack", "skin", "flask", "can", "vial", "paper wrap", "baggie", "jerry can", "scuttle",
  "canister", "bowl", "plate", "cup", "glass", "tank"];
export const CONTAINER_KEEP = new Set(["a can of pepper spray", "a sack of coarse cloth"]);
const CONTAINER_RE = new RegExp(`^an? (${[...CONTAINER_WORDS].sort((a, b) => b.length - a.length).join("|")}) of (.+)$`);
/** "a bottle of claret" -> {name: "claret", container: "a bottle"}; null when the name holds no container. */
export function splitContainer(name) {
  if ( CONTAINER_KEEP.has(name) ) return null;
  const m = CONTAINER_RE.exec(name);
  return m ? {name: m[2], container: `a ${m[1]}`} : null;
}


