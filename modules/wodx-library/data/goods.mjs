/** Default source by category; every other category defaults to history. */
const KIND_SOURCE = {drugs: "v20drugs", faith: "faith", occult: "occult"};

/** "4>1600:2>1850:1" or 3 to [[year, tier], ...] from the first year on. */
export function parseValue(v, from) {
  if ( typeof v === "number" ) return [[from, v]];
  const [base, ...rest] = String(v).split(">");
  return [[from, Number(base)], ...rest.map(s => s.split(":").map(Number))];
}

/** A good's value tier in a given year (the tier in force then). */
export function valueAt(good, year) {
  let t = good.steps[0][1];
  for ( const [y, v] of good.steps ) if ( year >= y ) t = v;
  return t;
}

/** Eras whose years overlap the span [from, to]. */
export function erasFor(from, to) {
  return ERAS.filter(e => ERA_YEARS[e][0] <= to && ERA_YEARS[e][1] >= from);
}

const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");


/**
 * The goods as objects. Fill by place and era reads name, kind, eras and small (pocket or jacket); the rest is the
 * backend tagging, gathered in good.tags.
 */
export const GOODS = ROWS.map(([name, kind, from, to, conceal, value, src]) => {
  const eras = erasFor(from, to);
  const steps = parseValue(value ?? 0, from);
  const g = {id: slug(name), name, kind, from, to, eras, conceal, small: conceal === "P" || conceal === "J",
    source: src ?? KIND_SOURCE[kind] ?? "hist", steps};
  g.values = Object.fromEntries(eras.map(e => [e, valueAt(g, Math.max(ERA_YEARS[e][0], from))]));
  g.value = eras.length ? g.values[eras[0]] : valueAt(g, from);
  const [use, kindStacks] = BEHAVIOUR_OVERRIDES[name] ?? KIND_BEHAVIOUR[kind] ?? ["kept", false];
  const listed = STACK_SIZES[name];
  const stacks = Boolean(listed) || kindStacks;
  const plural = listed?.[0] ?? (stacks ? measurePlural(name) : null);
  g.stack = stacks ? {plural, min: listed?.[1] ?? 1, max: listed?.[2] ?? (plural ? 3 : 1)} : null;
  const uses = USES_OVERRIDES[name] ?? KIND_BEHAVIOUR[kind]?.[3] ?? [];
  Object.assign(g, {use, stacks, uses, sheet: KIND_BEHAVIOUR[kind]?.[2] ?? "Item"});
  g.tags = {category: kind, era: eras, value: g.values, use, stacks, stack: g.stack, uses, conceal};
  return g;
});
