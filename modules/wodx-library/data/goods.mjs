/** "a sack of grain" -> "sacks of grain"; null when the name is not "a <measure> of ...". */
export function measurePlural(name) {
  const m = /^an? ([a-z]+) of (.+)$/.exec(name);
  if ( !m ) return null;
  return `${PLURAL_UNITS[m[1]] ?? (/(s|x|ch|sh)$/.test(m[1]) ? m[1] + "es" : m[1] + "s")} of ${m[2]}`;
}

/**
 * The line for n of a good: "a bronze coin", "7 bronze coins", "claret", "claret (3)". Nothing starts in a container
 * (Ben, 2026-11-12): a good once written "a bottle of claret" is just claret, and a bottle is a good of its own.
 */
export function stackLine(g, n = 1) {
  if ( g?.container ) return n > 1 ? `${g.name} (${n})` : g.name;
  return n > 1 && g.stack?.plural ? `${n} ${g.stack.plural}` : g.name;
}

/** A list line without its count: "claret (3)" -> {name: "claret", count: 3}. Older "claret (in 3 bottles)" lines still read. */
export function readLine(line) {
  const s = String(line ?? "").trim();
  const c = /^(.+?)\s*\((\d+)\)$/.exec(s);
  if ( c ) return {name: c[1], count: Number(c[2])};
  const m = /^(.+?)\s*\(in (an?|\d+) [^)]+\)$/.exec(s);
  if ( !m ) return {name: s, count: 1};
  return {name: m[1], count: /^\d+$/.test(m[2]) ? Number(m[2]) : 1};
}

