/** "4>1600:2>1850:1" or 3 to [[year, tier], ...] from the first year on. */
export function parseValue(v, from) {
  if ( typeof v === "number" ) return [[from, v]];
  const [base, ...rest] = String(v).split(">");
  return [[from, Number(base)], ...rest.map(s => s.split(":").map(Number))];
}

/** A good's value tier in a given year (the tier in force then). */
export function valueAt(good, year) {
  let t = good.steps[0][1];
  for ( const [y, v] of good.steps ) if ( year >= y ) t = v;
  return t;
}

/** Eras whose years overlap the span [from, to]. */
export function erasFor(from, to) {
  return ERAS.filter(e => ERA_YEARS[e][0] <= to && ERA_YEARS[e][1] >= from);
}

const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/**
 * The goods as objects. Fill by place and era reads name, kind, eras and small; the rest is the backend tagging:
 * tags.category "kind/sub", tags.era (era ids), tags.value (tier in the good's first era), plus the tier per era.
 */
export const GOODS = ROWS.map(([name, sub, from, to, small, value, src]) => {
  const [kind, , subValue, subSrc] = SUBS[sub] ?? [];
  const eras = erasFor(from, to);
  const steps = parseValue(value ?? subValue ?? 0, from);
  const g = {id: slug(name), name, kind, sub, from, to, eras, small: !!small, source: src ?? subSrc ?? "hist", steps};
  g.values = Object.fromEntries(eras.map(e => [e, valueAt(g, Math.max(ERA_YEARS[e][0], from))]));
  g.value = eras.length ? g.values[eras[0]] : valueAt(g, from);
  g.tags = {category: `${kind}/${sub}`, era: eras, value: g.values};
  return g;
});
