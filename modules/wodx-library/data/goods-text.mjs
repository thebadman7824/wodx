/** {name: [{need, text}]} */
export const DETAILS = (() => {
  const out = {};
  for ( const line of DETAIL_RAW.split("\n") ) {
    const m = /^(.+?) \| (\d+) \| (.+)$/.exec(line.trim());
    if ( m ) (out[m[1]] ??= []).push({need: Number(m[2]), text: m[3]});
  }
  return out;
})();
export const detailsOf = name => DETAILS[name] ?? [];

/** {name: [{from, text}]} sorted by year. */
export const DESC = (() => {
  const out = {};
  for ( const line of DESC_RAW.split("\n") ) {
    const m = /^(?:@(-?\d+) )?(.+?) \| (.+)$/.exec(line.trim());
    if ( !m ) continue;
    (out[m[2]] ??= []).push({from: m[1] === undefined ? -Infinity : Number(m[1]), text: m[3]});
  }
  for ( const k of Object.keys(out) ) out[k].sort((a, b) => a.from - b.from);
  return out;
})();

/** The wording for a good in a year (the latest form that has begun). */
export function describe(name, year = null) {
  const forms = DESC[name];
  if ( !forms?.length ) return "";
  if ( year === null || !Number.isFinite(Number(year)) ) return forms[0].text;
  let pick = forms[0];
  for ( const f of forms ) if ( f.from <= Number(year) ) pick = f;
  return pick.text;
}
