/** A good's tags by its row name: {station: [words], style, material}, or null. */
export function tagsOf(name) {
  const t = TAGS[name];
  if ( !t ) return null;
  return {station: [...t[0]].map(c => STATIONS[c]).filter(Boolean), style: t[1], material: t[2]};
}
